const fs = require("node:fs/promises");
const path = require("node:path");
const assert = require("node:assert/strict");
let running = false;

exports.run = async (window, userData) => {
  if (running) return;
  running = true;
  const run = code => window.webContents.executeJavaScript(`(async () => (${code}))()`);
  const delay = ms => new Promise(resolve => setTimeout(resolve, ms));
  const marker = name => path.join(userData, name);
  const wait = async name => {
    for (let i = 0; i < 500; i++) {
      try { await fs.access(marker(name)); return; } catch { await delay(40); }
    }
    throw new Error(`Missing MCP test stage ${name}`);
  };
  const poll = async (code, label) => {
    for (let i = 0; i < 200; i++) { if (await run(code)) return; await delay(40); }
    throw new Error(`MCP UI assertion timed out: ${label}`);
  };
  const count = n => `(await window.easydrawDesktop.getMcpRuntimeStatus()).clientCount === ${n}`;
  const enabled = flag => `(await window.easydrawDesktop.getMcpRuntimeStatus()).enabled === ${flag}`;
  const clickSwitch = () => run(`document.querySelector('.mcp-service-row [role="switch"]').click()`);
  const screenshot = async name => {
    await delay(150); // Let Chromium paint after DOM assertions and modal changes.
    const target = path.resolve("qa", name);
    await fs.mkdir(path.dirname(target), { recursive: true });
    await fs.writeFile(target, (await window.webContents.capturePage()).toPNG());
  };
  await run(`document.querySelector('[aria-label="打开 AI 设置"]').click()`);
  await poll(`document.querySelector('.mcp-service-row [role="switch"]')?.disabled === false`, "loaded switch");
  assert(await run(enabled(false)));
  assert(await run(`document.querySelector('.mcp-service-row [role="switch"]').getAttribute('aria-checked') === 'false'`));
  assert(await run(`document.querySelectorAll('[data-mcp-client]').length === 0`));
  assert(await run(`!('connectCodex' in window.easydrawDesktop) && !('connectPi' in window.easydrawDesktop) && !('connectDeepSeek' in window.easydrawDesktop)`));
  await assert.rejects(fs.access(marker("mcp-bridge.json")));
  const info = await run(`window.easydrawDesktop.getMcpConnectionInfo()`);
  assert.equal(info.transport, "stdio");
  assert.equal(info.config.mcpServers.easydraw.env.EASYDRAW_BRIDGE_DESCRIPTOR, marker("mcp-bridge.json"));
  assert(!JSON.stringify(info).includes('"token"'));
  assert.match(info.skillHash, /^[a-f0-9]{64}$/);
  await poll(`localStorage.getItem('easydraw.skills.acknowledgedHash') === ${JSON.stringify(info.skillHash)}`, "first-use skill baseline");
  assert(await run(`!document.querySelector('.skill-update-dot') && !document.querySelector('.mcp-copy-skill')`));
  assert(await run(`!document.querySelector('.mcp-dialog__heading p, .mcp-service-status') && !document.querySelector('.mcp-dialog').textContent.includes('客户端名称由对方报告')`));
  assert(await run(`!document.querySelector('.mcp-dialog').textContent.includes('复制接入信息')`));
  await run(`document.querySelector('.mcp-actions button').click()`);
  await poll(`Boolean(document.querySelector('.mcp-guide-dialog'))`, "guide modal");
  assert(await run(`document.querySelector('.mcp-guide-dialog .dialog-heading p').textContent === '复制下方指南交给你的Agent执行' && !document.querySelector('.mcp-guide').textContent.includes('人工接入')`));
  assert(await run(`document.querySelector('.mcp-command').textContent.includes('ELECTRON_RUN_AS_NODE') && document.querySelector('.mcp-guide').textContent.includes('Agent 执行步骤')`));
  assert(await run(`getComputedStyle(document.querySelector('.mcp-panel')).overflowY === 'auto'`));
  assert(await run(`document.activeElement === document.querySelector('.mcp-guide-dialog .dialog-close')`));
  assert(await run(`(() => { const button = document.querySelector('.mcp-guide-footer .button--primary'); button.focus(); button.dispatchEvent(new KeyboardEvent('keydown', { key: 'Tab', bubbles: true, cancelable: true })); return document.activeElement === document.querySelector('.mcp-guide-dialog .dialog-close'); })()`));
  // Capture clipboard requests in this isolated process; never overwrite the OS clipboard.
  const { clipboard } = require("electron");
  let copiedText = "", failCopy = false;
  const captureClipboard = text => {
    if (failCopy) throw new Error("Injected clipboard failure");
    copiedText = text;
  };
  clipboard.writeText = captureClipboard;
  assert.equal(clipboard.writeText, captureClipboard);
  await run(`document.querySelector('.mcp-guide-footer .button--primary').click()`);
  await poll(`document.querySelector('.mcp-guide-footer [role="status"]').textContent.includes('完整接入指南已复制')`, "full guide copied");
  for (const content of await run(`[...document.querySelectorAll('.mcp-dialog__heading h2, .mcp-dialog__heading p, .mcp-guide h3, .mcp-guide p, .mcp-guide li, .mcp-guide code')].map(element => element.textContent)`)) {
    assert(copiedText.includes(content), "Clipboard omitted visible guide content");
  }
  assert.deepEqual(JSON.parse(copiedText.match(/```json\n([\s\S]*?)\n```/)[1]), info.config);
  assert(copiedText.includes(info.skillPath));
  await screenshot("mcp-access-guide.png");
  failCopy = true;
  await run(`document.querySelector('.mcp-guide-footer .button--primary').click()`);
  await poll(`document.querySelector('.mcp-guide-footer [role="status"]').textContent.includes('无法复制接入指南')`, "visible copy failure");
  await run(`document.querySelector('.mcp-panel').scrollTop = document.querySelector('.mcp-panel').scrollHeight`);
  assert(await run(`document.querySelector('.mcp-skill-path').getBoundingClientRect().bottom <= document.querySelector('.mcp-dialog').getBoundingClientRect().bottom`));
  await screenshot("mcp-access-guide-bottom.png");
  await run(`document.querySelector('.mcp-panel').scrollTop = 0`);
  await run(`document.querySelector('.mcp-guide-dialog').dispatchEvent(new KeyboardEvent('keydown', { key: 'Escape', bubbles: true, cancelable: true }))`);
  await poll(`Boolean(document.querySelector('.mcp-service-row')) && !document.querySelector('.mcp-guide-dialog')`, "back to access modal");
  assert(await run(`document.activeElement === document.querySelector('.mcp-actions button')`));
  await screenshot("mcp-access-off.png");
  assert(await run(`document.querySelector('.mcp-actions button').disabled === false`));
  failCopy = false;
  const reloadApp = async () => {
    const loaded = new Promise(resolve => window.webContents.once("did-finish-load", resolve));
    window.webContents.reload();
    await loaded;
    await poll(`Boolean(document.querySelector('[aria-label="打开 AI 设置"]'))`, "restored app");
    await run(`document.querySelector('[aria-label="打开 AI 设置"]').click()`);
    await poll(`document.querySelector('.mcp-service-row [role="switch"]')?.disabled === false`, "restored AI modal");
  };
  await run(`localStorage.setItem('easydraw.skills.acknowledgedHash', 'previous-skill-content')`);
  await reloadApp();
  await poll(`Boolean(document.querySelector('.skill-update-dot'))`, "updated skill dot");
  const mcpDialogHeight = await run(`document.querySelector('.mcp-dialog').getBoundingClientRect().height`);
  await run(`document.querySelector('[aria-label="关闭 AI 设置"]').click()`);
  await run(`document.querySelector('[aria-label="打开 AI 设置"]').click()`);
  assert(await run(`Boolean(document.querySelector('.skill-update-dot'))`));
  await run(`document.querySelector('#ai-tab-mcp').dispatchEvent(new KeyboardEvent('keydown', { key: 'ArrowRight', bubbles: true, cancelable: true }))`);
  await poll(`Boolean(document.querySelector('.mcp-acknowledge-skill'))`, "updated Skills tab");
  assert.equal(await run(`document.querySelector('.mcp-dialog').getBoundingClientRect().height`), mcpDialogHeight);
  await screenshot("ai-skills-updated.png");
  assert(await run(`document.querySelector('#ai-panel-skills').scrollHeight <= document.querySelector('#ai-panel-skills').clientHeight`), "Skills content fits the fixed dialog height: " + await run(`JSON.stringify({height:document.querySelector('#ai-panel-skills').clientHeight,content:document.querySelector('#ai-panel-skills').scrollHeight})`));
  assert(await run(`document.activeElement === document.querySelector('#ai-tab-skills')`));
  assert(await run(`document.querySelector('.mcp-copy-skill').getBoundingClientRect().top > document.querySelector('.mcp-skill-path').getBoundingClientRect().bottom`));
  assert.deepEqual(await run(`[...document.querySelectorAll('.mcp-skill-card .mcp-actions button')].map(button => button.textContent)`),["更新Skills","复制 Skills 目录"]);
  assert(await run(`document.querySelector('#ai-panel-skills > p').textContent.includes('Skills 随 EasyDraw 更新，但不会自动推送给 Agent。') && document.querySelector('#ai-panel-skills > p').textContent.includes('~/.agents/skills')`));
  assert(await run(`!document.querySelector('.mcp-skill-card > strong, .mcp-skill-update') && !document.querySelector('#ai-panel-skills').textContent.includes('如何使用')`));
  assert(await run(`document.querySelector('.mcp-skill-heading h3').textContent === ${JSON.stringify(path.basename(info.skillPath))}`));
  assert(await run(`document.querySelector('.mcp-skill-heading .mcp-skill-update-label').textContent === '有更新' && document.querySelector('.mcp-skill-heading .mcp-acknowledge-skill').getAttribute('aria-label') === '标记为已读'`));
  assert(await run(`document.querySelector('.mcp-acknowledge-skill').textContent.trim() === '标记为已读' && Boolean(document.querySelector('.mcp-acknowledge-skill svg circle'))`));
  assert(await run(`getComputedStyle(document.querySelector('.mcp-skill-card')).borderTopStyle === 'solid' && getComputedStyle(document.querySelector('.mcp-tabs-row')).borderBottomWidth === '0px'`));
  await run(`document.querySelector('.mcp-copy-skill').click()`);
  await poll(`document.querySelector('.mcp-skill-notice')?.textContent.includes('Skills 目录已复制')`, "copy directory from Skills tab");
  assert.equal(copiedText, info.skillPath);
  assert(await run(`Boolean(document.querySelector('.skill-update-dot'))`));
  // Exercise copying in a temporary home; never update the user's installed skills.
  const { ipcMain } = require("electron");
  const { installBundledSkill } = require("../../electron/skill-installation.cjs");
  const skillTarget = path.join(userData,"home/.agents/skills/easydraw-product-sketch");
  const otherSkill = path.join(userData,"home/.agents/skills/user-skill/SKILL.md");
  await fs.mkdir(path.dirname(otherSkill),{recursive:true});
  await fs.writeFile(otherSkill,"User skill");
  await assert.rejects(fs.access(skillTarget));
  let failUpdate = true, finishUpdate;
  const updateReady = new Promise(resolve => {finishUpdate=resolve;});
  ipcMain.removeHandler("easydraw:skills:update");
  ipcMain.handle("easydraw:skills:update",async () => {
    if (failUpdate) return false;
    await updateReady;
    await installBundledSkill({source:info.skillPath,destination:skillTarget});
    return true;
  });
  await run(`document.querySelector('.mcp-update-skill').click()`);
  await poll(`document.querySelector('.mcp-skill-notice')?.textContent.includes('无法更新 Skills') && !document.querySelector('.mcp-update-skill').disabled`,"visible skill update failure");
  assert(await run(`Boolean(document.querySelector('.skill-update-dot'))`));
  failUpdate = false;
  await run(`document.querySelector('.mcp-update-skill').click()`);
  await poll(`document.querySelector('.mcp-update-skill').disabled && document.querySelector('.mcp-copy-skill').disabled`,"updating skills disables duplicate actions");
  finishUpdate();
  await poll(`document.querySelector('.mcp-skill-notice')?.textContent.includes('Skills 已更新到公共目录') && !document.querySelector('.skill-update-dot') && !document.querySelector('.mcp-update-skill').disabled`,"skill installed and update acknowledged");
  for (const file of ["SKILL.md","references/protocol.md","agents/openai.yaml"]) assert.deepEqual(await fs.readFile(path.join(skillTarget,file)),await fs.readFile(path.join(info.skillPath,file)));
  await fs.writeFile(path.join(skillTarget,"SKILL.md"),"Old version");
  await run(`document.querySelector('.mcp-update-skill').click()`);
  await poll(`document.querySelector('.mcp-skill-notice')?.textContent.includes('Skills 已更新到公共目录') && !document.querySelector('.mcp-update-skill').disabled`,"existing skill updated");
  assert.deepEqual(await fs.readFile(path.join(skillTarget,"SKILL.md")),await fs.readFile(path.join(info.skillPath,"SKILL.md")));
  assert.equal(await fs.readFile(otherSkill,"utf8"),"User skill");
  await screenshot("ai-skills-installed.png");
  await run(`localStorage.setItem('easydraw.skills.acknowledgedHash', 'previous-skill-content')`);
  await reloadApp();
  await run(`document.querySelector('#ai-tab-skills').click()`);
  await poll(`Boolean(document.querySelector('.mcp-acknowledge-skill'))`,"restore unread skill for acknowledgement tests");
  await run(`(() => { window.savedSkillSetItem = Storage.prototype.setItem; Storage.prototype.setItem = function(key, value) { if (key === 'easydraw.skills.acknowledgedHash') throw new Error('Injected storage failure'); return window.savedSkillSetItem.call(this, key, value); }; })()`);
  await run(`document.querySelector('.mcp-acknowledge-skill').click()`);
  await poll(`document.querySelector('.mcp-skill-notice')?.textContent.includes('无法保存 Skills 确认状态')`, "acknowledgement failure");
  assert(await run(`Boolean(document.querySelector('.skill-update-dot')) && localStorage.getItem('easydraw.skills.acknowledgedHash') === 'previous-skill-content'`));
  await run(`(() => { Storage.prototype.setItem = window.savedSkillSetItem; })()`);
  await run(`document.querySelector('.mcp-acknowledge-skill').click()`);
  await poll(`!document.querySelector('.skill-update-dot') && !document.querySelector('.mcp-acknowledge-skill, .mcp-skill-update-label')`, "acknowledged update");
  assert(await run(`localStorage.getItem('easydraw.skills.acknowledgedHash') === ${JSON.stringify(info.skillHash)}`));
  await reloadApp();
  assert(await run(`!document.querySelector('.skill-update-dot')`));
  await run(`document.querySelector('#ai-tab-skills').click()`);
  await poll(`Boolean(document.querySelector('.mcp-skill-card'))`, "Skills tab after reload");
  assert(await run(`!document.querySelector('.mcp-acknowledge-skill') && document.querySelector('.mcp-copy-skill').disabled === false`));
  await screenshot("ai-skills.png");
  await run(`document.querySelector('#ai-tab-skills').dispatchEvent(new KeyboardEvent('keydown', { key: 'ArrowLeft', bubbles: true, cancelable: true }))`);
  await poll(`Boolean(document.querySelector('.mcp-service-row'))`, "MCP tab after Skills");
  await clickSwitch(); await poll(enabled(true), "enabled");
  await poll(`document.querySelector('.mcp-service-row [role="switch"]').disabled === false`, "saved enable preference");
  await fs.writeFile(marker("connection-info.json"), JSON.stringify(info));
  await fs.writeFile(marker("mcp-enabled"), "ready");

  await wait("mcp-both-ready");
  await poll(`document.querySelectorAll('[data-mcp-client]').length === 2`, "dynamic clients");
  assert(await run(`document.querySelector('[data-mcp-client="Future Agent A"]') && document.querySelector('[data-mcp-client="Future Agent B"]')`));
  await screenshot("mcp-access-connected.png");
  const guideButtonTop = await run(`document.querySelector('#ai-panel-mcp .mcp-actions').getBoundingClientRect().top`);
  await run(`(() => { const list = document.querySelector('.mcp-client-list'); for (let i = 0; i < 30; i++) { const row = list.firstElementChild.cloneNode(true); row.removeAttribute('data-mcp-client'); row.dataset.layoutFixture = ''; list.append(row); } })()`);
  assert(await run(`getComputedStyle(document.querySelector('.mcp-clients')).borderTopStyle === 'solid' && getComputedStyle(document.querySelector('.mcp-clients')).borderBottomStyle === 'solid'`));
  assert(await run(`(() => { const list = document.querySelector('.mcp-client-list'); list.scrollTop = list.scrollHeight; return list.scrollHeight > list.clientHeight && list.scrollTop > 0 && document.querySelector('#ai-panel-mcp').scrollTop === 0; })()`), "only the client list scrolls");
  assert.equal(await run(`document.querySelector('#ai-panel-mcp .mcp-actions').getBoundingClientRect().top`), guideButtonTop);
  assert(await run(`document.querySelector('#ai-panel-mcp .mcp-actions').getBoundingClientRect().bottom <= document.querySelector('.mcp-dialog').getBoundingClientRect().bottom`));
  await screenshot("mcp-access-many-clients.png");
  await run(`(() => { document.querySelectorAll('[data-layout-fixture]').forEach(row => row.remove()); document.querySelector('.mcp-client-list').scrollTop = 0; })()`);
  await clickSwitch(); await poll(enabled(false), "revoked");
  await poll(`document.querySelectorAll('[data-mcp-client]').length === 0`, "no stale clients");
  await assert.rejects(fs.access(marker("mcp-bridge.json")));
  await fs.writeFile(marker("mcp-disabled"), "ready");
  await wait("mcp-revocation-checked");
  await clickSwitch(); await poll(enabled(true), "re-enabled");
  await poll(`document.querySelector('.mcp-service-row [role="switch"]').disabled === false`, "saved re-enable preference");
  await fs.writeFile(marker("mcp-reenabled"), "ready");
  await wait("mcp-reconnected-ready");
  await poll(count(2), "both reconnected");
  await poll(`document.querySelectorAll('[data-mcp-client]').length === 2`, "reconnected identities");
  await fs.writeFile(marker("mcp-reconnected-checked"), "ready");
  await wait("mcp-one-ready");
  await poll(count(1), "one disconnected");
  await poll(`document.querySelectorAll('[data-mcp-client]').length === 1 && !document.querySelector('[data-mcp-client="Future Agent B"]')`, "removed identity");
  await clickSwitch(); await poll(enabled(false), "final revocation");
  await poll(`document.querySelector('.mcp-service-row [role="switch"]').disabled === false`, "saved preference");
  assert.equal(JSON.parse(await fs.readFile(marker("mcp-settings.json"), "utf8")).enabled, false);
  await fs.writeFile(marker("mcp-finished"), "ready");
  console.log("MCP_DESKTOP_UI_OK: default off, generic guide, dynamic identities, revocation, re-enable and disconnect");
  await wait("mcp-quit");
  require("electron").app.quit();
};
