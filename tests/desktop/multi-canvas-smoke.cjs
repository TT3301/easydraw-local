const assert = require("node:assert/strict");
const fs = require("node:fs/promises");
const path = require("node:path");
exports.run = async (window, userData) => {
  window.show(); window.focus();
  const run = async source => { try { return await window.webContents.executeJavaScript(source); } catch (error) { await fs.writeFile("/private/tmp/easydraw-multi-canvas-failure.png", (await window.webContents.capturePage()).toPNG()); throw new Error(`UI action failed: ${source}: ${error.message}`); } };
  const delay = ms => new Promise(resolve => setTimeout(resolve, ms));
  const settle = async () => delay(160);
  const saved = async () => { await delay(1150); return run("window.easydrawDesktop.openProject()"); };
  const finishRename = async () => { await run(`document.querySelector('.canvas-tree-row input')?.dispatchEvent(new KeyboardEvent('keydown', { key: 'Enter', bubbles: true }))`); await settle(); };
  const choose = async label => { await run(`Array.from(document.querySelectorAll('.canvas-context-menu button')).find(n => n.textContent === ${JSON.stringify(label)}).click()`); await settle(); };
  await run(`document.querySelector('[aria-label="展开左侧边栏"]')?.click()`); await settle();
  assert(await run(`!!document.querySelector('[data-panel-tab="canvases"]')`));
  assert(!await run(`!!document.querySelector('[data-panel-tab="pages"]')`));
  assert(await run(`document.querySelector('.tree-count').textContent === '1 个画布'`));
  assert(await run(`getComputedStyle(document.querySelector('.canvas-panel')).padding === '0px'`));
  assert(!await run(`!!document.querySelector('.tree-root-drop, .tree-symbol, .tree-toggle, .tree-search')`));
  await run(`document.querySelector('.tree-toolbar [aria-label="新建画布"]').click()`); await settle(); await finishRename();
  let snapshot = await saved();
  assert(snapshot.document.tree.every(n => n.type === "canvas" && n.parentId === null));
  const original = snapshot.document.tree[0], canvas = snapshot.document.tree[1];
  assert.equal(snapshot.document.canvases[canvas.id].scene.elements.length, 0);
  const originalElements = snapshot.document.canvases[original.id].scene.elements;
  assert(await run(`document.querySelector('.tree-count').textContent === '2 个画布'`));
  // Buttons are hidden until hover or keyboard focus, including on the selected row.
  await run(`document.activeElement?.blur()`);
  window.webContents.sendInputEvent({ type: "mouseMove", x: 1040, y: 650 }); await settle();
  assert(await run(`getComputedStyle(document.querySelector('.canvas-tree-row.is-active .tree-more')).opacity === '0'`));
  const rowBounds = await run(`(() => {const r = document.querySelector('.canvas-tree-row.is-active').getBoundingClientRect(); return {x:r.x+20,y:r.y+17}})()`);
  window.webContents.sendInputEvent({ type: "mouseMove", ...rowBounds }); await settle();
  assert(await run(`getComputedStyle(document.querySelector('.canvas-tree-row.is-active .tree-more')).opacity === '1'`));
  await run(`document.querySelector('.canvas-tree-row.is-active .tree-more').click()`); await settle();
  assert(await run(`document.querySelector('.canvas-context-menu').parentElement === document.body && getComputedStyle(document.querySelector('.canvas-context-menu')).position === 'fixed'`));
  assert.equal(await run(`document.querySelectorAll('.canvas-context-menu [role="menuitem"]').length`), 3);
  await run(`document.querySelector('.canvas-context-menu').dispatchEvent(new KeyboardEvent('keydown',{key:'ArrowDown',bubbles:true}))`);
  assert.equal(await run(`document.activeElement.textContent`), "复制画布");
  await run(`document.querySelector('.canvas-context-menu').dispatchEvent(new KeyboardEvent('keydown',{key:'Escape',bubbles:true}))`); await settle();
  assert(!await run(`!!document.querySelector('.canvas-context-menu')`));
  await run(`document.querySelector('.canvas-tree-row.is-active .tree-more').click()`); await settle();
  await run(`document.querySelector('.tree-count').dispatchEvent(new PointerEvent('pointerdown',{bubbles:true}))`); await settle();
  assert(!await run(`!!document.querySelector('.canvas-context-menu')`));
  // Search is revealed by the header button, filters by name and closes with Escape.
  await run(`document.querySelector('.tree-toolbar [aria-label="搜索画布"]').click()`); await settle();
  await run(`(() => { const input = document.querySelector('.tree-search'); Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(input,${JSON.stringify(canvas.name)}); input.dispatchEvent(new Event('input',{bubbles:true})); })()`); await settle();
  assert.equal(await run(`document.querySelectorAll('.tree-name').length`), 1);
  await run(`document.querySelector('.tree-search').dispatchEvent(new KeyboardEvent('keydown',{key:'Escape',bubbles:true}))`); await settle();
  assert.equal(await run(`document.querySelectorAll('.tree-name').length`), 2);
  await run(`document.querySelector(".App-toolbar__shape-tools-trigger").click()`); await settle();
  await run(`document.querySelector('[data-testid="toolbar-shape-menu-rectangle"]').click()`); await settle();
  window.webContents.sendInputEvent({ type: "mouseMove", x: 720, y: 330 });
  window.webContents.sendInputEvent({ type: "mouseDown", x: 720, y: 330, button: "left", clickCount: 1 });
  window.webContents.sendInputEvent({ type: "mouseMove", x: 820, y: 390, button: "left" });
  window.webContents.sendInputEvent({ type: "mouseUp", x: 820, y: 390, button: "left", clickCount: 1 });
  await settle();
  await run(`Array.from(document.querySelectorAll('.tree-name')).find(n => n.title === ${JSON.stringify(original.name)}).click()`); await settle();
  snapshot = await saved();
  assert.equal(snapshot.document.canvases[canvas.id].scene.elements.length, 1, "last manual edit survives switching");
  assert.deepEqual(snapshot.document.canvases[original.id].scene.elements, originalElements, "original canvas is isolated");
  const clickCanvas = async (name) => {
    require("electron").app.focus({ steal: true });
    window.focus(); window.webContents.focus();
    await settle();
    const point = await run(`(() => {const r=Array.from(document.querySelectorAll('.tree-name')).find(n=>n.title===${JSON.stringify(name)}).getBoundingClientRect();return {x:Math.round(r.x+20),y:Math.round(r.y+r.height/2)};})()`);
    window.webContents.sendInputEvent({type:"mouseDown",...point,button:"left",clickCount:1});
    window.webContents.sendInputEvent({type:"mouseUp",...point,button:"left",clickCount:1});
    await settle();
    assert(await run(`document.activeElement === document.querySelector('.canvas-wrap .easydraw')`),"switching must return keyboard focus to the canvas: "+await run(`JSON.stringify({focused:document.hasFocus(),active:[document.activeElement.tagName,document.activeElement.className],overlays:[...document.querySelectorAll('[role="dialog"], [role="menu"], [role="listbox"], .dropdown-menu, .popover')].filter(e=>e.getClientRects().length).map(e=>[e.tagName,e.className])})`));
  };
  await clickCanvas(canvas.name);
  await clickCanvas(original.name);
  const viewport = () => run(`(() => {const d=document.querySelector('.canvas-wrap').dataset;return [Number(d.viewportScrollX),Number(d.viewportScrollY)];})()`);
  const beforePan = await viewport();
  window.webContents.sendInputEvent({type:"keyDown",keyCode:"Space"});
  await settle();
  window.webContents.sendInputEvent({type:"mouseDown",x:1000,y:500,button:"left",clickCount:1});
  window.webContents.sendInputEvent({type:"mouseMove",x:1080,y:550,button:"left"});
  window.webContents.sendInputEvent({type:"mouseUp",x:1080,y:550,button:"left",clickCount:1});
  window.webContents.sendInputEvent({type:"keyUp",keyCode:"Space"});
  await settle();
  assert.notDeepEqual(await viewport(),beforePan,"space-drag must pan immediately after switching canvases");
  await run(`Array.from(document.querySelectorAll('.tree-name')).find(n => n.title === ${JSON.stringify(canvas.name)}).click()`); await settle();
  await run(`document.querySelector('.canvas-tree-row.is-active .tree-more').click()`); await settle(); await choose("重命名");
  await run(`(() => { const input = document.querySelector('.canvas-tree-row input'); Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(input,'原型画布'); input.dispatchEvent(new Event('input',{bubbles:true})); })()`); await settle(); await finishRename();
  await run(`document.querySelector('.canvas-tree-row.is-active .tree-more').click()`); await settle(); await choose("复制画布");
  snapshot = await saved();
  const copied = snapshot.document.tree.find(n => n.name.includes("副本"));
  assert(copied); assert.equal(snapshot.document.canvases[copied.id].scene.elements.length, 1);
  assert.notEqual(snapshot.document.canvases[copied.id].scene.elements[0].id, snapshot.document.canvases[canvas.id].scene.elements[0].id);
  await run(`window.confirm = () => true; document.querySelector('.canvas-tree-row.is-active .tree-more').click()`); await settle(); await choose("删除");
  snapshot = await saved(); assert.equal(snapshot.document.tree.length, 2);
  await run(`document.querySelector('.history-control [aria-label="撤销"]').click()`); await settle();
  snapshot = await saved(); assert.equal(snapshot.document.tree.length, 3); assert(snapshot.document.canvases[copied.id]);
  window.webContents.sendInputEvent({ type: "keyDown", keyCode: "O", modifiers: ["meta"] });
  window.webContents.sendInputEvent({ type: "keyUp", keyCode: "O", modifiers: ["meta"] });
  await delay(500);
  assert(await run(`document.querySelector('.canvas-tree-row.is-active .tree-name').title === ${JSON.stringify(copied.name)}`), "last canvas restores on reopen");
  assert.equal(await run(`document.querySelectorAll('.tree-name').length`), 3);
  await run(`document.querySelector('.canvas-tree-row.is-active .tree-more').click()`); await settle();
  await fs.writeFile(process.env.EASYDRAW_MULTI_CANVAS_SCREENSHOT || path.join(process.env.TMPDIR || "/tmp", "easydraw-multi-canvas.png"), (await window.webContents.capturePage()).toPNG());
  await run(`document.querySelector('.canvas-context-menu').dispatchEvent(new KeyboardEvent('keydown',{key:'Escape',bubbles:true}))`);
  await require("./workspace-interaction-smoke.cjs").run(window);
  await fs.writeFile(path.join(userData, "multicanvas-ready"), "ready");
  console.log("MULTI_CANVAS_DESKTOP_SMOKE_OK: flat list, count, hover, popup, keyboard, search, manual edit, switching, rename, duplicate, delete, undo, save and reopen");
};
